def task(
    id: str,
    stage: str,
    title: str,
    kind: str,
    prompt: str,
    starter: str,
    *,
    cases: tuple[tuple[str, str], ...] = (),
    answer: str = "",
    hint: str = "",
    explanation: str = "",
) -> Exercise:
    return Exercise(
        id=id,
        stage=stage,
        title=title,
        kind=kind,
        prompt=prompt,
        starter=starter,
        tests=tuple(Case(stdin, expected) for stdin, expected in cases),
        answer=answer,
        hint=hint,
        explanation=explanation,
    )


